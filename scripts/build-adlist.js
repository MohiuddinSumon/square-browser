#!/usr/bin/env node
// Copyright (c) 2025 SquareBrowser Contributors
//
// Builds the ad / tracker domain list that ships inside the app.
//
//   node scripts/build-adlist.js
//
// Source: StevenBlack/hosts "unified hosts" (MIT licensed, see
// modules/square-adblock/THIRD_PARTY.md). The result is bundled as an Android asset and loaded
// by the native request filter, so blocking works offline and no request is ever sent to a
// third party at runtime. Rebuild it before a release to refresh the list.
//
// Steps: download -> keep plain domains -> drop anything in never-block.txt -> add
// extra-domains.txt -> drop sub-domains already covered by a listed parent -> sort -> write.

const fs = require('fs');
const path = require('path');

const SOURCE_URL = 'https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts';
const HERE = __dirname;
const OUT = path.join(HERE, '..', 'modules', 'square-adblock', 'android', 'src', 'main', 'assets', 'adlist.txt');

const readList = (file) =>
  fs
    .readFileSync(path.join(HERE, 'adlist', file), 'utf8')
    .split(/\r?\n/)
    .map((l) => l.trim().toLowerCase())
    .filter((l) => l && !l.startsWith('#'));

const DOMAIN = /^(?=.{4,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
const IGNORE = new Set(['localhost.localdomain', 'broadcasthost', 'local', 'ip6-localhost']);

// Popular sites used to sanity-check the finished list: none of these may end up blocked.
const MUST_NOT_BLOCK = [
  'google.com', 'www.google.com', 'fonts.googleapis.com', 'fonts.gstatic.com', 'ajax.googleapis.com',
  'youtube.com', 'm.youtube.com', 'i.ytimg.com', 'rr1---sn-a5mekn7s.googlevideo.com', 'facebook.com',
  'static.xx.fbcdn.net', 'instagram.com', 'twitter.com', 'abs.twimg.com', 'github.com',
  'raw.githubusercontent.com', 'cdn.jsdelivr.net', 'unpkg.com', 'cdnjs.cloudflare.com',
  'wikipedia.org', 'upload.wikimedia.org', 'reddit.com', 'www.redditstatic.com', 'stackoverflow.com',
  'amazon.com', 'm.media-amazon.com', 's3.amazonaws.com', 'microsoft.com', 'apple.com', 'icloud.com',
  'netflix.com', 'vimeo.com', 'player.vimeo.com', 'imgur.com', 'i.imgur.com', 'paypal.com',
  'linkedin.com', 'whatsapp.com', 'bbc.com', 'nytimes.com', 'cloudflare.com', 'challenges.cloudflare.com',
  'accounts.google.com', 'play.google.com', 'maps.googleapis.com', 'apis.google.com',
];

function blockedBy(set, host) {
  let h = host;
  for (;;) {
    if (set.has(h)) return h;
    const i = h.indexOf('.');
    if (i < 0) return null;
    h = h.slice(i + 1);
  }
}

async function main() {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error('download failed: ' + res.status);
  const text = await res.text();

  const domains = new Set();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim();
    if (!line) continue;
    const parts = line.split(/\s+/);
    if (parts.length < 2 || !/^(0\.0\.0\.0|127\.0\.0\.1)$/.test(parts[0])) continue;
    const d = parts[1].toLowerCase();
    if (IGNORE.has(d) || !DOMAIN.test(d)) continue;
    domains.add(d);
  }
  const fromSource = domains.size;

  const neverBlock = new Set(readList('never-block.txt'));
  let removedAllow = 0;
  for (const d of neverBlock) if (domains.delete(d)) removedAllow++;

  const extras = readList('extra-domains.txt').filter((d) => DOMAIN.test(d));
  for (const d of extras) domains.add(d);

  // Drop sub-domains that a listed parent already covers (the engine matches parent domains).
  const kept = [];
  for (const d of domains) {
    const parent = d.slice(d.indexOf('.') + 1);
    if (parent.includes('.') && blockedBy(domains, parent)) continue;
    kept.push(d);
  }
  kept.sort();

  // Safety net: popular sites must not be blocked.
  const finalSet = new Set(kept);
  const bad = MUST_NOT_BLOCK.filter((h) => blockedBy(finalSet, h));
  if (bad.length) {
    console.error('Refusing to write: these must-not-block hosts would be blocked:');
    for (const h of bad) console.error('  ' + h + '  (via ' + blockedBy(finalSet, h) + ')');
    console.error('Add the offending root to scripts/adlist/never-block.txt (or narrow the entry).');
    process.exit(1);
  }

  const header = [
    '# SquareBrowser ad / tracker domain list (generated by scripts/build-adlist.js; do not edit).',
    '# Source: StevenBlack/hosts (MIT) + scripts/adlist/extra-domains.txt. See THIRD_PARTY.md.',
    '# Matching is by domain suffix: a listed domain also blocks all of its sub-domains.',
  ];
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header.join('\n') + '\n' + kept.join('\n') + '\n');

  console.log('source domains      :', fromSource);
  console.log('removed (never-block):', removedAllow);
  console.log('extras added        :', extras.length);
  console.log('written              :', kept.length, 'domains,', Math.round(fs.statSync(OUT).size / 1024), 'KB ->', path.relative(process.cwd(), OUT));
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
